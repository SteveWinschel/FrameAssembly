//! Because FrameAssembly defines over 400 uppercase protocol names and modifier keywords, users
//! may still choose lowercase or contextual names (such as `dns`, `ms`, `get`, or `server`) for
//! `HOST` and `FLOW` identifiers. This module provides [`parse_spanned_ident`], [`parse_ident`],
//! [`parse_any_str`], and [`unescape_string`] to resolve identifiers, string-like arguments, and
//! C-style hex/Unicode escape sequences (`\r`, `\n`, `\t`, `\\`, `\"`, `\'`, `\xHH`, `\uXXXX`).

